import fs from 'node:fs';
import Papa from 'papaparse';
import { profileDataset } from '../src/analytics/profiler/datasetProfiler';
import { detectSemanticRoles } from '../src/analytics/profiler/semanticDetector';
import { resolveDomainRulePack } from '../src/analytics/rules/rulePacks';
import { composeUniversalDashboard } from '../src/analytics/composer/dashboardComposer';

async function main() {
  const text = fs.readFileSync('public/datasets/ecommerce_sales_5k.csv', 'utf8');
  const parsed = Papa.parse(text, { header: true, skipEmptyLines: 'greedy' });
  const headers = (parsed.meta.fields || []).map(h => h.replace(/^\ufeff/, '').trim()).filter(Boolean);
  const rows = parsed.data as Record<string, any>[];

  console.log(`Audited ${rows.length} rows across ${headers.length} headers.`);
  const profile = profileDataset(headers, rows);
  const semantics = detectSemanticRoles(profile);
  const rulePack = resolveDomainRulePack(profile, semantics);
  const model = await composeUniversalDashboard('ecommerce_sales_5k', rows, profile, semantics, rulePack);

  console.log(`Domain Classification: ${model.domainClassification} (${(model.domainConfidence * 100).toFixed(1)}%)`);
  console.log('\n--- KPI CARDS ---');
  model.kpiCards.forEach(k => console.log(`[${k.id}] ${k.label}: ${k.formattedValue} | Formula: ${k.calculationFormula} | Additivity: ${k.additivity}`));

  console.log('\n--- CHARTS GENERATED BY RULEPACK ---');
  model.charts.forEach(c => console.log(`[${c.id}] ${c.title} | Type: ${c.chartType} | Dim: ${c.dimensionLabel} | Metric: ${c.metricLabel} | Points: ${c.data.length}`));
}

main().catch(console.error);
